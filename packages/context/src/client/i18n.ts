/**
 * The locale chain dsh-context got from the harness, as a local resolver:
 * the active dictionary, then en, then the key itself, with `{name}`
 * interpolation over the params.
 * @param locale - the active UI locale.
 * @returns the bound translate the view kit is built from.
 */
export function createContextTranslate(locale: ContextLocale): Translate {
  const table = locale === 'zh' ? DICT_ZH : DICT_EN
  return (key, params) => {
    let s = table[key] ?? DICT_EN[key] ?? key
    if (params) for (const k in params) s = s.replace('{' + k + '}', String(params[k]))
    return s
  }
}
